"""
threading = лёгкий способ параллельно выполнять I/O операции.
Для CPU-bound задач многопоточность не ускоряет Python из-за GIL.
Всегда используйте Lock при работе с общими ресурсами.

Каждый поток выполняется одновременно, но в Python из-за GIL настоящий параллелизм по CPU ограничен.
Идеально подходит для I/O-bound задач (сеть, чтение/запись файлов), потому что в таком случае GIL захватывает другой поток.
Для CPU-bound задач лучше использовать multiprocessing.

## Основные объекты:

| Примитив                         | Что делает                                                                           | Когда использовать                                                                | Пример использования                                          |
| -------------------------------- | ------------------------------------------------------------------------------------ | --------------------------------------------------------------------------------- | ------------------------------------------------------------- |
| **Lock**                         | Простейшая блокировка, позволяет только одному потоку работать с критической секцией | Защита **одного ресурса** (например, общий счётчик)                               | `with lock: counter += 1`                                     |
| **RLock**                        | Рекурсивная блокировка — поток может захватывать несколько раз                       | Когда **один поток вызывает функции, которые сами захватывают Lock**              | `rlock.acquire()` внутри функции и снова в вызываемой функции |
| **Semaphore**                    | Ограничивает количество потоков, выполняющих участок кода одновременно               | Контроль **количества одновременных подключений, доступ к ограниченному ресурсу** | `semaphore = threading.Semaphore(3)`                          |
| **BoundedSemaphore**             | То же, что Semaphore, но не позволяет увеличить счётчик выше установленного          | То же самое, плюс предотвращает ошибки логики                                     | `with sem:` …                                                 |
| **Event**                        | Поток может ждать события (`wait`) или оповещать другие потоки (`set`)               | Когда один поток **ожидает сигнал от другого**                                    | `event.wait()` / `event.set()`                                |
| **Condition**                    | Сложная синхронизация, wait/notify между потоками                                    | Когда поток должен ждать **определённого состояния**                              | `cond.wait()` / `cond.notify()`                               |
| **Barrier**                      | Ожидание группы потоков, пока все достигнут точки                                    | Когда нужно, чтобы **несколько потоков стартовали или закончили вместе**          | `barrier.wait()`                                              |
| **Thread.join()**                | Ожидание завершения потока                                                           | Чтобы основной поток дождался окончания других                                    | `t.join()`                                                    |
| **current_thread()**             | Получить объект текущего потока                                                      | Логирование или идентификация потока                                              | `threading.current_thread().name`                             |
| **active_count() / enumerate()** | Список/количество активных потоков                                                   | Мониторинг                                                                        | `threading.enumerate()`                                       |


current_thread()	Возвращает объект текущего потока.
active_count()	Количество активных потоков.
enumerate()	Список всех активных потоков.

Потоки позволяют выполнять I/O-bound задачи параллельно.
Для CPU-bound задач лучше использовать multiprocessing, чтобы обойти GIL.
Lock, RLock, Semaphore, Event, Condition — инструменты для безопасной работы с общими ресурсами.
Thread.start() → запуск, Thread.join() → ожидание завершения.
"""

import os
import threading
import time
import random


def target_func(name):
    print(f"Target {name}, PID: {os.getpid()}", flush=True)
    t = random.random()
    time.sleep(t)


def start_and_join():
    # В Python (x) — это просто x в скобках.
    # Чтобы сделать tuple из одного элемента, нужна запятая: (x,).
    # В args ожидается итерируемый объект, поэтому скобки и запятая нужны, иначе будет строка 'Thread-1' в скобках.
    t1 = threading.Thread(target=target_func, args=("Thread-1",))
    t2 = threading.Thread(target=target_func, args=("Thread-2",))

    t1.start()
    t2.start()

    # Ожидание завершения потоков
    t1.join()
    # (можно указать timeout, после таймаута процесс может всё ещё выполняться, но основной поток продолжит работу.)
    t2.join(timeout=1)

    print("all threads finished")


if __name__ == "__main__":
    start_and_join()
    print()
